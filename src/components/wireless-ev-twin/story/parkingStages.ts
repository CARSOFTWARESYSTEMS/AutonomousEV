const chargingNow = () => {
  const f = focus();
  const ch = f?.bayId ? facility().chargers.get(f.bayId) : undefined;
  return !!ch && ch.session?.parkingSessionId === f?.id && (ch.sim.state.phase === "charging" || ch.sim.state.phase === "optimizing" || ch.sim.state.phase === "grid-limited");
};

