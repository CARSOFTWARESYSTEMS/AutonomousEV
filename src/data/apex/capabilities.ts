/**
 * The specialist capabilities an integrated rocket program needs.
 *
 * A capability says what it is for, what it connects to, what it delivers and
 * what evidence shows it is done. Who provides it is not written here: that is
 * partner-capabilities.ts, so a capability can have no partner yet, one, or
 * many. Its status is derived from those relationships, never typed by hand.
 */

