// The formal engineering model registry. One entry per model in the engine,
// with its equations, inputs and outputs in SI units, assumptions, validity
// domain, numerical method, limitations, fidelity, validation status and the
// verification checks that exercise it. The interface, the documentation and
// the verification suite all read this list.

export type Fidelity = "F0" | "F1" | "F2" | "F3" | "F4" | "F5";

export const FIDELITY: Record<Fidelity, { name: string; text: string }> = {
  F0: { name: "Conceptual visualisation", text: "Shows what happens, not how much. No quantitative claim." },
  F1: { name: "Analytical model", text: "Closed-form or quasi-static equations with declared assumptions." },
  F2: { name: "Dynamic numerical model", text: "Time-stepped states (battery, thermal, motion, estimation) integrated numerically." },
  F3: { name: "Detailed circuit or field simulation", text: "Switching-level circuit or finite-element field simulation." },
  F4: { name: "Experimentally calibrated", text: "Parameters fitted to measurements and validated within a stated operating range." },
  F5: { name: "Connected prototype twin", text: "Synchronised with a physical prototype's live telemetry." },
};

/**
 * Validation status. Connectivity and accuracy are independent: a model is
 * never "Experimentally validated" because data flows into it.
 */
export type ValidationStatus = "Planned" | "Designed" | "Implemented" | "Tested" | "Analytically verified" | "Experimentally validated" | "Blocked";

export interface Quantity {
  symbol: string;
  name: string;
  unit: string;
}

export interface ModelEntry {
  id: string;
  name: string;
  version: string;
  domain: string;
  description: string;
  equations: string[];
  inputs: Quantity[];
  outputs: Quantity[];
  assumptions: string[];
  validity: string;
  method: string;
  dependencies: string[];
  limitations: string[];
  fidelity: Fidelity;
  status: ValidationStatus;
  /** Verification checks (ids in benchmarks.ts). */
  tests: string[];
  components: string[];
  lessons: string[];
  experiments: string[];
  /** Where it is implemented. */
  implementation: string;
}

const q = (symbol: string, name: string, unit: string): Quantity => ({ symbol, name, unit });

