// Sensor and telemetry model (WPT-DATA-001).
//
// Every telemetry value is produced the way an instrument produces it: the
// simulated true value passes through a gain error, offset and noise, is
// quantised by an ADC, then converted back with the stored calibration. Each
// reading carries its raw counts, unit, timestamp, source, sampling rate,
// calibration, quality flag, uncertainty, model version and transformation
// history, and a data mode. Nothing here is LIVE hardware telemetry: with no
// physical prototype connected, readings are SIMULATED (or ESTIMATED where a
// state estimator produced them), and turn STALE or INVALID when checks fail.
import { createRng, type Rng } from "./math";

export type DataMode = "SIMULATED" | "RECORDED" | "LIVE" | "ESTIMATED" | "STALE" | "INVALID";

export const DATA_MODES: Record<DataMode, string> = {
  SIMULATED: "Generated by a mathematical or numerical model.",
  RECORDED: "Previously captured experimental data, imported.",
  LIVE: "Fresh data from an explicitly connected physical prototype.",
  ESTIMATED: "Calculated by a state-estimation model.",
  STALE: "Older than its freshness threshold.",
  INVALID: "Failed a validation or quality check.",
};

export interface SensorSpec {
  id: string;
  label: string;
  unit: string;
  /** Where the value is measured. */
  source: string;
  sampleHz: number;
  /** ADC resolution and the engineering range it spans. */
  bits: number;
  rangeMin: number;
  rangeMax: number;
  /** Instrument errors, in engineering units (noise is 1σ). */
  gainError: number;
  offset: number;
  noise: number;
  /** Calibration applied when converting counts back (a calibrated instrument has gain 1, offset 0 after correction). */
  calGain: number;
  calOffset: number;
  /** Plausibility range; outside it the reading is INVALID. */
  validMin: number;
  validMax: number;
  /** Readings older than this are STALE, s. */
  staleAfter: number;
  estimated?: boolean;
  transformation: readonly string[];
}

export interface Reading {
  id: string;
  label: string;
  unit: string;
  raw: number;
  value: number;
  timestamp: number;
  mode: DataMode;
  quality: "good" | "suspect" | "bad";
  /** Expanded uncertainty (≈95 %), engineering units. */
  uncertainty: number;
  source: string;
  sampleHz: number;
  calibration: string;
  modelVersion: string;
  history: readonly string[];
}

export const SENSOR_MODEL_VERSION = "WPT-DATA-001 v1.0.0";

const lsb = (s: SensorSpec) => (s.rangeMax - s.rangeMin) / (2 ** s.bits - 1);

/** A bank of sampled sensors. Deterministic for a seed. */
export class SensorBank {
  private rng: Rng;
  private last = new Map<string, Reading>();
  private nextSample = new Map<string, number>();
  constructor(
    readonly specs: readonly SensorSpec[],
    seed: number,
  ) {
    this.rng = createRng(seed ^ 0x5bd1e995);
  }

  /** Samples every sensor that is due at time t from the true values. Disconnected sensors stop updating. */
  sample(t: number, truth: Record<string, number>, disconnected: ReadonlySet<string> = new Set()): void {
    for (const s of this.specs) {
      const due = this.nextSample.get(s.id) ?? 0;
      if (t + 1e-9 < due) continue;
      this.nextSample.set(s.id, due + 1 / s.sampleHz > t ? due + 1 / s.sampleHz : t + 1 / s.sampleHz);
      if (disconnected.has(s.id) || truth[s.id] === undefined) continue;
      const measured = truth[s.id] * (1 + s.gainError) + s.offset + s.noise * this.rng.normal();
      const counts = Math.round((measured - s.rangeMin) / lsb(s));
      const saturated = counts <= 0 || counts >= 2 ** s.bits - 1;
      const raw = Math.max(0, Math.min(2 ** s.bits - 1, counts));
      const value = (s.rangeMin + raw * lsb(s)) * s.calGain + s.calOffset;
      const invalid = saturated || value < s.validMin || value > s.validMax;
      this.last.set(s.id, {
        id: s.id,
        label: s.label,
        unit: s.unit,
        raw,
        value,
        timestamp: t,
        mode: invalid ? "INVALID" : s.estimated ? "ESTIMATED" : "SIMULATED",
        quality: invalid ? "bad" : "good",
        uncertainty: 2 * Math.hypot(s.noise, lsb(s) / Math.sqrt(12), Math.abs(s.gainError * truth[s.id]) + Math.abs(s.offset)),
        source: s.source,
        sampleHz: s.sampleHz,
        calibration: `gain ${s.calGain.toFixed(4)}, offset ${s.calOffset} ${s.unit}`,
        modelVersion: SENSOR_MODEL_VERSION,
        history: [`ADC ${s.bits}-bit over ${s.rangeMin}…${s.rangeMax} ${s.unit}`, ...s.transformation, saturated ? "ADC saturated" : "range check passed"],
      });
    }
  }

  /** The latest reading of every sensor at time t, with freshness applied. */
  readings(t: number): Reading[] {
    const out: Reading[] = [];
    for (const s of this.specs) {
      const r = this.last.get(s.id);
      if (!r) continue;
      const stale = t - r.timestamp > s.staleAfter;
      out.push(stale && r.mode !== "INVALID" ? { ...r, mode: "STALE", quality: "suspect" } : r);
    }
    return out;
  }

  reading(id: string, t: number): Reading | undefined {
    return this.readings(t).find((r) => r.id === id);
  }
}

const spec = (s: Omit<SensorSpec, "calGain" | "calOffset" | "transformation"> & Partial<Pick<SensorSpec, "calGain" | "calOffset" | "transformation">>): SensorSpec => ({
  calGain: 1,
  calOffset: 0,
  transformation: ["linear calibration"],
  ...s,
});

