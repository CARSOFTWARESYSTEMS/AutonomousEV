// Regenerates the Smart Parking replicated research results (SP-RES-002):
//   docs/wireless-ev-charging-digital-twin/SMART_PARKING_EXPERIMENT_RESULTS.md
//   docs/wireless-ev-charging-digital-twin/data/smart-parking-research-results.json
// Run: SP_RESEARCH_WRITE=1 npx vitest run scripts/smart-parking-research.test.ts --environment node
// Skipped (writes nothing) in the ordinary test run.
import { mkdirSync, writeFileSync } from "node:fs";
import { it } from "vitest";
import { METRIC_INFO, type MetricKey, replicationsFor, RESEARCH_ASSUMPTIONS, RESEARCH_MODEL, RESEARCH_POLICIES, RESEARCH_VERSION, runExperiment, SCENARIOS, type Summary } from "../src/lib/wireless-charging/smart-parking/research";

const REPLICATIONS = 50;

it.skipIf(!process.env.SP_RESEARCH_WRITE)(
  "writes the Smart Parking research results",
  () => {
    const dir = new URL("../docs/wireless-ev-charging-digital-twin/", import.meta.url).pathname;
    const started = performance.now();
    const results = SCENARIOS.map((s) => runExperiment(s.id, REPLICATIONS));
    const elapsed = (performance.now() - started) / 1000;
    mkdirSync(`${dir}data`, { recursive: true });
    writeFileSync(`${dir}data/smart-parking-research-results.json`, JSON.stringify({ generated: "SP-RES-002", replications: REPLICATIONS, results }, null, 1));

    const name = (id: string) => RESEARCH_POLICIES.find((p) => p.id === id)!.name;
    const info = (k: MetricKey) => METRIC_INFO.find((m) => m.key === k)!;
    const scale = (k: MetricKey) => (info(k).unit === "fraction" ? 100 : 1);
    const unit = (k: MetricKey) => (info(k).unit === "fraction" ? "%" : info(k).unit);
    const digits = (k: MetricKey) => (["meanSearchS", "throughputPerHour", "fairness"].includes(k) ? 2 : ["revenueParkingINR", "revenueChargingINR", "p95WaitS"].includes(k) ? 0 : 1);
    const ci = (s: Summary, k: MetricKey) => (Number.isFinite(s.mean) ? `${(s.mean * scale(k)).toFixed(digits(k))} [${(s.ciLow * scale(k)).toFixed(digits(k))}, ${(s.ciHigh * scale(k)).toFixed(digits(k))}]` : "—");
    const diff = (s: Summary, k: MetricKey) => {
      if (!Number.isFinite(s.mean)) return "—";
      const sign = s.ciLow > 0 || s.ciHigh < 0 ? "" : " (n.s.)";
      return `${s.mean * scale(k) >= 0 ? "+" : ""}${(s.mean * scale(k)).toFixed(digits(k))} [${(s.ciLow * scale(k)).toFixed(digits(k))}, ${(s.ciHigh * scale(k)).toFixed(digits(k))}]${sign}`;
    };
    const main: MetricKey[] = ["throughputPerHour", "meanSearchS", "meanWaitS", "p95WaitS", "utilisation", "requestFulfilment", "energyFulfilment", "energyDeliveredKWh", "peakGridKW", "solarUtilisation", "fairness", "abandoned", "revenueParkingINR", "revenueChargingINR"];
    const paired: MetricKey[] = ["meanSearchS", "requestFulfilment", "energyDeliveredKWh", "peakGridKW", "solarUtilisation", "throughputPerHour"];
    const md: string[] = [
      "# Smart Parking — replicated research results (SP-RES-002)",
      "",
      `Generated by \`scripts/smart-parking-research.test.ts\` from \`src/lib/wireless-charging/smart-parking/research.ts\` (model ${RESEARCH_MODEL}, version ${RESEARCH_VERSION}). **Every value is SIMULATED** on synthetic demand with declared assumptions; none is a measurement of a real facility and none supports a real-world performance claim. The method is in SMART_PARKING_TEST_PLAN.md §2–§3.`,
      "",
      `Regenerate: \`SP_RESEARCH_WRITE=1 npx vitest run scripts/smart-parking-research.test.ts --environment node\` (≈ ${Math.ceil(elapsed)} s on the development machine). Full results, every metric with mean, SD, 5th, 50th and 95th percentiles and confidence intervals: \`data/smart-parking-research-results.json\`.`,
      "",
      "## Configuration",
      "",
      `- **Replications:** ${REPLICATIONS} per policy and scenario. Seeds are \`${results[0].seeds[0]} + 101·k\` for k = 0…${REPLICATIONS - 1}. Every policy sees the same seeds, so arrivals, vehicles and patience are identical (common random numbers); comparisons are paired.`,
      `- **Facility:** 12 bays (8 conventional including 1 accessible, 4 wireless), the default layout. The day runs 07:00–19:00 with a ${RESEARCH_ASSUMPTIONS.stepS} s step.`,
      `- **Equal resources for every policy:**`,
      `  - the same bays, and any vehicle may use any bay (the accessible bay needs a permit);`,
      `  - an ${RESEARCH_ASSUMPTIONS.chargerKW} kW battery-side charger in each wireless bay, with grid-to-battery efficiency ${RESEARCH_ASSUMPTIONS.gridToBattery};`,
      `  - the same canopy PV, site import limit, ${RESEARCH_ASSUMPTIONS.baseLoadW / 1000} kW base load and IN tariff;`,
      `  - a compatible EV that asked to charge charges whenever it is in a working wireless bay.`,
      `- **Queue:** ${RESEARCH_ASSUMPTIONS.queueCapacity} places at the entry. Patience is exponential with a ${RESEARCH_ASSUMPTIONS.meanPatienceS / 60}-minute mean.`,
      `- **Manual baseline (a declared assumption, not an observation):** drivers take the first free bay they pass, and ${RESEARCH_ASSUMPTIONS.cruisingMissShare * 100} % miss and loop the aisle. Search time is the drive at 70 % of aisle speed plus 6 s.`,
      `- **Peak import:** the largest ${RESEARCH_ASSUMPTIONS.peakAveragingS / 60}-minute average grid import.`,
      `- **Fairness:** Jain's index of per-request energy fulfilment (delivered / requested). Requests that got no wireless bay count as 0.`,
      `- **Fault recovery:** queued vehicle-minutes above the same seed's fault-free day, and the minutes after the fault until the queue matches that day for 10 consecutive minutes.`,
      "- **Notation:** values are means with their 95 % confidence interval [low, high] (Student t). Differences are paired against the manual baseline. *n.s.* means the interval includes zero.",
      "",
      "## Policies",
      "",
      ...RESEARCH_POLICIES.map((p) => `- **${p.name}** — ${p.text}`),
      "",
    ];
    for (const r of results) {
      md.push(`## ${r.scenario.name}`, "", r.scenario.text, "");
      md.push(`| Metric | ${r.policies.map((p) => name(p.policy)).join(" | ")} |`, `|---|${r.policies.map(() => "---").join("|")}|`);
      for (const k of main) md.push(`| ${info(k).name} (${unit(k)}) | ${r.policies.map((p) => ci(p.metrics[k], k)).join(" | ")} |`);
      if (r.policies[0].recovery) {
        md.push(`| Extra queued vehicle-minutes from the fault | ${r.policies.map((p) => `${p.recovery!.extraQueueVehMin.mean.toFixed(1)} [${p.recovery!.extraQueueVehMin.ciLow.toFixed(1)}, ${p.recovery!.extraQueueVehMin.ciHigh.toFixed(1)}]`).join(" | ")} |`);
        md.push(`| Recovery after the fault (min) | ${r.policies.map((p) => `${p.recovery!.recoveryMin.mean.toFixed(1)} [${p.recovery!.recoveryMin.ciLow.toFixed(1)}, ${p.recovery!.recoveryMin.ciHigh.toFixed(1)}]`).join(" | ")} |`);
      }
      md.push("", "Paired difference against the manual baseline (policy − manual):", "");
      md.push(`| Metric | ${r.policies.filter((p) => p.policy !== "manual").map((p) => name(p.policy)).join(" | ")} |`, `|---|${r.policies.filter((p) => p.policy !== "manual").map(() => "---").join("|")}|`);
      for (const k of paired) md.push(`| ${info(k).name} (${unit(k)}) | ${r.policies.filter((p) => p.policy !== "manual").map((p) => diff(p.vsManual[k], k)).join(" | ")} |`);
      md.push("");
    }
    // Sample size: the replications needed for ±5 % of the mean, from these runs.
    const normal = results.find((r) => r.scenario.id === "normal")!;
    md.push("## Sample size", "", `How many replications a ±5 % confidence half-width of the mean would need, estimated from the ${REPLICATIONS} normal-demand runs (n = (1.96·s / 0.05·x̄)²). Paired differences need fewer, because common random numbers remove most of the day-to-day variation.`, "");
    md.push(`| Metric | ${normal.policies.map((p) => name(p.policy)).join(" | ")} |`, `|---|${normal.policies.map(() => "---").join("|")}|`);
    for (const k of ["throughputPerHour", "meanWaitS", "energyDeliveredKWh", "peakGridKW", "solarUtilisation"] as MetricKey[]) md.push(`| ${info(k).name} | ${normal.policies.map((p) => String(replicationsFor(p.metrics[k].mean, p.metrics[k].sd))).join(" | ")} |`);
    md.push(
      "",
      `With ${REPLICATIONS} replications, the paired differences highlighted in SMART_PARKING_TEST_PLAN.md §2 have confidence intervals that exclude zero. Where an interval includes zero (*n.s.*), no difference is detectable at this sample size, and none is claimed.`,
      "",
      "## Limitations",
      "",
      "- **No vehicle motion or aisle congestion.** Search time does not delay the entry queue, so waiting time depends only on bay occupancy. The facility simulation (SP-SIM-001) models motion, and its runs are not part of these tables.",
      "- **Fixed charging power.** Charging is a constant 11 kW battery-side, with no CC–CV taper. Check SP-A09 bounds the error of this surrogate against the Station model at 3.5 % for a 30→80 % session.",
      "- **Synthetic inputs.** Demand, stays, the SOC on arrival, patience and driver behaviour are declared distributions, not data.",
      "- **No storage in the dispatch.** The research model has no battery storage; PV not used at the moment it is generated is counted as unused.",
      "- **Tariff.** Revenue uses the configured IN tariff, a representative placeholder (SMART_PARKING_INTERNATIONALIZATION.md). It predicts no behavioural response to price.",
    );
    writeFileSync(`${dir}SMART_PARKING_EXPERIMENT_RESULTS.md`, md.join("\n") + "\n");
  },
  600_000,
);
